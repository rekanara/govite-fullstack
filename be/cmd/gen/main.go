// Command gen writes the permission catalog and security limits from
// internal/policy into the frontend contracts package.
//
//	go run ./cmd/gen [out]   default ../fe/packages/contracts/src/generated.ts
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"govite/internal/policy"
)

func main() {
	out := "../fe/packages/contracts/src/generated.ts"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	if err := os.WriteFile(out, []byte(render()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", out)
}

func list(v []string) string {
	b, _ := json.Marshal(v)
	return strings.ReplaceAll(string(b), ",", ", ")
}

func render() string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	s := policy.Security
	w("// Code generated by be/cmd/gen from be/internal/policy. DO NOT EDIT.\n\n")
	w("export const SCOPES = %s as const\n", list(policy.Scopes))
	w("export const ACTIONS = %s as const\n", list(policy.Actions))
	w("export const RESOURCES = %s as const\n\n", list(policy.Resources))
	w("export const PERMISSIONS = [\n")
	for _, p := range policy.Permissions {
		w("  { resource: %q, action: %q },\n", p.Resource, p.Action)
	}
	w("] as const\n\n")
	w("export const SECURITY_POLICY = {\n")
	w("  passwordMinLength: %d,\n", s.PasswordMinLength)
	w("  passwordMaxLength: %d,\n", s.PasswordMaxLength)
	w("  accessTokenTtlMs: %d,\n", s.AccessTokenTTL.Milliseconds())
	w("  refreshTokenTtlMs: %d,\n", s.RefreshTokenTTL.Milliseconds())
	w("  passwordResetLinkTtlMs: %d,\n", s.PasswordResetLinkTTL.Milliseconds())
	w("  passwordResetCodeTtlMs: %d,\n", s.PasswordResetCodeTTL.Milliseconds())
	w("  inviteTtlMs: %d,\n", s.InviteTTL.Milliseconds())
	w("  emailVerificationTtlMs: %d,\n", s.EmailVerificationTTL.Milliseconds())
	w("  maxCodeAttempts: %d,\n", s.MaxCodeAttempts)
	w("} as const\n")
	return b.String()
}
